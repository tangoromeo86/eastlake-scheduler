'use strict';

// Builds the season calendar (Mon–Fri + Saturday, per week) from the season's
// configured start date, so a new season only needs `season.start` updated in
// season.json rather than a code change. Falls back to LEGACY_SEASON_WEEKS
// below when no start date is configured, which keeps pre-existing seasons
// working unchanged.
function buildSeasonWeeks(season) {
  const start = season && (season.start || season.start_date);
  if (!start || !/^\d{4}-\d{2}-\d{2}$/.test(start)) return LEGACY_SEASON_WEEKS;

  const weekCount = Number(season.weeks) > 0 ? Number(season.weeks) : LEGACY_SEASON_WEEKS.length;
  // Snap back to the Monday of the start date's week so weeks line up Mon–Sat.
  const d = new Date(start + 'T12:00:00Z');
  const dow = d.getUTCDay(); // 0=Sun
  d.setUTCDate(d.getUTCDate() - ((dow + 6) % 7));

  const iso = (dt) => dt.toISOString().slice(0, 10);
  const weeks = [];
  for (let w = 0; w < weekCount; w++) {
    const weekdays = [];
    for (let i = 0; i < 5; i++) {
      const day = new Date(d);
      day.setUTCDate(d.getUTCDate() + (w * 7) + i);
      weekdays.push(iso(day));
    }
    const sat = new Date(d);
    sat.setUTCDate(d.getUTCDate() + (w * 7) + 5);
    weeks.push({ week: w + 1, weekdays, saturday: iso(sat) });
  }
  return weeks;
}

